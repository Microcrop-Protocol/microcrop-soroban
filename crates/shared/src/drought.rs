//! `crop-drought-rdi-1.0`: the on-chain recompute of the drought index and the evidence
//! bounds `PayoutReceiver::submit_drought_determination` enforces.
//!
//! The index is the integer arithmetic of `calculateDroughtDamage` in
//! `microcrop-lit-oracle` `src/scoring/drought.shared.js` (origin/main `1bc2d9d`), steps 4-6:
//!
//! ```text
//! s1 = min(1000, 1000*w1/r1); d1 = 100 - s1/10; g1 = min(100,  40*d1/100)
//! s2 = min(1000, 1000*w2/r2); d2 = 100 - s2/10; g2 = min(100, 150*d2/100)
//! drought_damage = 100 - ((100-g1)*(100-g2))/100
//! ```
//!
//! All operands are non-negative, so Rust's truncating `/` on `u128` is floor division, as
//! JS BigInt `/` is. Ky 40/150 and the window layout are frozen by the methodology params
//! hash; a different index is a new methodology string, not a change here.

/// Length of growing period the methodology is defined for (FAO I&D 56, maize, East Africa).
pub const LGP_DAYS: u32 = 180;
/// W2 is DAP 71..110, so the dry-spell count inside it is at most 40 days.
pub const MAX_CDD_W2_DAYS: u32 = 40;
/// Upper bound on any rainfall value, centi-mm (10,000 m). Keeps `1000 * w` far from
/// overflow and rejects garbage evidence.
pub const MAX_RAIN_E2: u128 = 1_000_000_000;
/// The measurement window ends at DAP 110: season start + 110 days.
pub const SEASON_WINDOW_SECS: u64 = 110 * 86_400;
/// Seconds in a UTC day; `season_start_epoch` is a civil date at 00:00 UTC.
pub const SECONDS_PER_DAY: u64 = 86_400;
/// Ky for W1, x100 (FAO I&D 66 Table 2, maize, initial stage).
pub const KY1_E2: u128 = 40;
/// Ky for W2, x100 (FAO I&D 66 Table 2, maize, crop development).
pub const KY2_E2: u128 = 150;

fn min(a: u128, b: u128) -> u128 {
    if a < b {
        a
    } else {
        b
    }
}

/// Recompute the rdi-1.0 drought damage (whole percent, 0..=100) from the signed evidence.
/// `None` when a reference rainfall is zero (the oracle refuses that pixel) or a rainfall
/// value is above [`MAX_RAIN_E2`].
pub fn rdi_v1_drought_damage(w1: u128, r1: u128, w2: u128, r2: u128) -> Option<u32> {
    if r1 == 0 || r2 == 0 || w1 > MAX_RAIN_E2 || w2 > MAX_RAIN_E2 {
        return None;
    }
    let s1 = min(1000, 1000 * w1 / r1);
    let d1 = 100 - s1 / 10;
    let g1 = min(100, KY1_E2 * d1 / 100);
    let s2 = min(1000, 1000 * w2 / r2);
    let d2 = 100 - s2 / 10;
    let g2 = min(100, KY2_E2 * d2 / 100);
    let survival = ((100 - g1) * (100 - g2)) / 100;
    Some((100 - survival) as u32)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Generated by the ORACLE's own code: `calculateDroughtDamage` from
    /// `microcrop-lit-oracle` origin/main `1bc2d9d` `src/scoring/drought.shared.js`, run in a
    /// throwaway copy on synthetic archive bodies whose W1/W2 sums and 1991-2020 medians are
    /// the first four columns (2025-04-01 planting). Columns: w1, r1, w2, r2, droughtDamage.
    const JS_GRID: [[u32; 5]; 225] = include!("drought_grid.in");

    #[test]
    fn recompute_matches_the_oracle_js_over_a_grid() {
        for [w1, r1, w2, r2, dd] in JS_GRID {
            assert_eq!(
                rdi_v1_drought_damage(w1 as u128, r1 as u128, w2 as u128, r2 as u128),
                Some(dd),
                "w1={} r1={} w2={} r2={}",
                w1,
                r1,
                w2,
                r2
            );
        }
    }

    #[test]
    fn canonical_vector_and_edges() {
        // V1: W1 at normal, W2 at 70% of normal -> d2 = 30, g2 = 45 -> 45%.
        assert_eq!(rdi_v1_drought_damage(20_000, 20_000, 12_600, 18_000), Some(45));
        // The EVM fixture's rains (W1 12500/20000, W2 3000/18000) give 100, not its 45.
        assert_eq!(rdi_v1_drought_damage(12_500, 20_000, 3_000, 18_000), Some(100));
        // Surplus never creates damage; total failure is 100.
        assert_eq!(rdi_v1_drought_damage(99_999, 1, 99_999, 1), Some(0));
        assert_eq!(rdi_v1_drought_damage(0, 1, 0, 1), Some(100));
        // Refused inputs.
        assert_eq!(rdi_v1_drought_damage(1, 0, 1, 1), None);
        assert_eq!(rdi_v1_drought_damage(1, 1, 1, 0), None);
        assert_eq!(rdi_v1_drought_damage(MAX_RAIN_E2 + 1, 1, 1, 1), None);
        // The extremes do not overflow.
        assert_eq!(
            rdi_v1_drought_damage(MAX_RAIN_E2, 1, MAX_RAIN_E2, 1),
            Some(0)
        );
        assert_eq!(
            rdi_v1_drought_damage(0, MAX_RAIN_E2, 0, u128::MAX),
            Some(100)
        );
    }
}
